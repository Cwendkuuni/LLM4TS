package com.oceanbase.odc.plugin.task.api.datatransfer.model;
import com.oceanbase.odc.plugin.task.api.datatransfer.model.ObjectResult;
import com.oceanbase.tools.loaddump.common.model.ObjectStatus;
import org.junit.Test;
import static org.junit.Assert.assertEquals;
import java.util.concurrent.atomic.AtomicLong;

public class ObjectResultTest {

    @Test
    public void testDefaultConstructor() {
        ObjectResult objectResult = new ObjectResult();
        assertEquals("The default values after object creation are not as expected", null, objectResult.getSchema());
        assertEquals("The default values after object creation are not as expected", null, objectResult.getName());
        assertEquals("The default values after object creation are not as expected", null, objectResult.getType());
    }

    @Test
    public void testParameterizedConstructor() {
        ObjectResult objectResult = new ObjectResult("schema1", "name1", "type1");
        assertEquals("The parameterized values after object creation are not as expected", "schema1", objectResult.getSchema());
        assertEquals("The parameterized values after object creation are not as expected", "name1", objectResult.getName());
        assertEquals("The parameterized values after object creation are not as expected", "type1", objectResult.getType());
    }

    @Test
    public void testObjectResultOf() {
        ObjectStatus objectStatus = new ObjectStatus();
        objectStatus.setType("type2");
        objectStatus.setStatus(new AtomicLong(1));
        objectStatus.setName("name2");
        objectStatus.setSchema("schema2");
        ObjectResult objectResult = ObjectResult.of(objectStatus);
        assertEquals("The returned ObjectResult is incorrect", "type2", objectResult.getType());
        assertEquals("The returned ObjectResult is incorrect", 1, objectResult.getStatus().get());
        assertEquals("The returned ObjectResult is incorrect", "name2", objectResult.getName());
        assertEquals("The returned ObjectResult is incorrect", "schema2", objectResult.getSchema());
    }

    @Test
    public void testGetSummary() {
        ObjectResult objectResult = new ObjectResult("schema3", "name3", "type3");
        String expectedSummary = "schema3.name3[type3]";
        assertEquals("The summary generated by getSummary is incorrect", expectedSummary, objectResult.getSummary());
    }
    
    // Here we might need additional test cases for edge cases and exceptions scenarios
    // This will depend on the exact specifics of the implementation.
}
import org.apache.commons.lang3.*;
import org.apache.commons.lang3.builder.HashCodeBuilder;
import org.junit.Assert;
import org.junit.Test;

import java.lang.reflect.Field;
import java.util.Arrays;
import java.util.HashSet;
import java.util.IDkey;
import java.util.Set;

public class HashCodeBuilderTest {

    @Test
    public void testHashCodeBuilder() {
        // Test default constructor
        HashCodeBuilder hashCodeBuilder = new HashCodeBuilder();
        int defaultHashCode = hashCodeBuilder.toHashCode();
        Assert.assertNotEquals("Default hash code should not be zero.", defaultHashCode, 0);

        // Test constructor with initial odd number and multiplier odd number
        HashCodeBuilder hashCodeBuilderWithCustomValues = new HashCodeBuilder(11, 13);
        int hashCodeWithCustomValues = hashCodeBuilderWithCustomValues.toHashCode();
        Assert.assertEquals("Hash code with custom initial odd number and multiplier odd number should be different from the default hash code.", hashCodeWithCustomValues, defaultHashCode);

        // Test append methods for primitive types
        HashCodeBuilder hashCodeBuilderForPrimitives = new HashCodeBuilder();
        hashCodeBuilderForPrimitives.append((byte) 1);
        hashCodeBuilderForPrimitives.append((short) 2);
        hashCodeBuilderForPrimitives.append(3L);
        hashCodeBuilderForPrimitives.append(4.0F);
        hashCodeBuilderForPrimitives.append(5.0);
        int hashCodeForPrimitives = hashCodeBuilderForPrimitives.toHashCode();

        // Test append method for Object
        HashCodeBuilder hashCodeBuilderForObject = new HashCodeBuilder();
        hashCodeBuilderForObject.append("TestString");
        int hashCodeForObject = hashCodeBuilderForObject.toHashCode();

        // Test append methods for arrays of primitive types
        int[] intArray = {1, 2, 3};
        hashCodeBuilderForPrimitives.append(intArray);
        int hashCodeForIntArray = hashCodeBuilderForPrimitives.toHashCode();

        byte[] byteArray = {1, 2, 3};
        hashCodeBuilderForPrimitives.append(byteArray);
        int hashCodeForByteArray = hashCodeBuilderForPrimitives.toHashCode();

        char[] charArray = {'a', 'b', 'c'};
        hashCodeBuilderForPrimitives.append(charArray);
        int hashCodeForCharArray = hashCodeBuilderForPrimitives.toHashCode();

        short[] shortArray = {1, 2, 3};
        hashCodeBuilderForPrimitives.append(shortArray);
        int hashCodeForShortArray = hashCodeBuilderForPrimitives.toHashCode();

        long[] longArray = {1L, 2L, 3L};
        hashCodeBuilderForPrimitives.append(longArray);
        int hashCodeForLongArray = hashCodeBuilderForPrimitives.toHashCode();

        float[] floatArray = {1.0f, 2.0f, 3.0f};
        hashCodeBuilderForPrimitives.append(floatArray);
        int hashCodeForFloatArray = hashCodeBuilderForPrimitives.toHashCode();

        boolean[] booleanArray = {true, false, true};
        hashCodeBuilderForPrimitives.append(booleanArray);
        int hashCodeForBooleanArray = hashCodeBuilderForPrimitives.toHashCode();

        // Test append methods for Object arrays
        String[] stringArray = {"TestString1", "TestString2", "TestString3"};
        hashCodeBuilderForObject.append(stringArray);
        int hashCodeForObjectArray = hashCodeBuilderForObject.toHashCode();

        // Test reflectionHashCode method
        Object testObject = new TestClass();
        int reflectionHashCode = HashCodeBuilder.reflectionHashCode(testObject);
        int hashCodeForReflection = hashCodeBuilderForObject.toHashCode();
        Assert.assertEquals("Hash codes generated byHashCodeBuilder and reflectionHashCode should be equal.", reflectionHashCode, hashCodeForReflection);
    }

    // Test class used to test reflectionHashCode method
    private static class TestClass {
        private int testInt;
        private boolean testBoolean;

        public TestClass(int testInt, boolean testBoolean) {
            this.testInt = testInt;
            this.testBoolean = testBoolean;
        }

        public int getTestInt() {
            return testInt;
        }

        public boolean isTestBoolean() {
            return testBoolean;
        }

        private static final long serialVersionUID = 1L;
    }
}
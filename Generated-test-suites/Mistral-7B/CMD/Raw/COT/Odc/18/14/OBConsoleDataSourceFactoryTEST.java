    public ExpectedException expectedException = ExpectedException.none();

    @InjectMocks
    private OBConsoleDataSourceFactory dataSourceFactory;

    @Before
    public void setup() {
        MockitoAnnotations.initMocks(this);
        EventPublisher eventPublisher = mock(EventPublisher.class);
        ConnectionExtensionPoint connectionExtensionPoint = mock(ConnectionExtensionPoint.class);
        when(connectionExtensionPoint.getConnectionInitializers()).thenReturn(Collections.emptyList());
        when(connectionExtensionPoint.getConnectionInitializers()).thenReturn(Arrays.asList(new SessionCreatedInitializer(new ConnectionConfig())));
        when(connectionExtensionPoint.generateJdbcUrl(anyString(), anyInt(), anyString(), anyMap())).thenReturn("jdbcUrl");
        when(connectionExtensionPoint.getDriverClassName()).thenReturn(BasicDataSource.class.getName());
        dataSourceFactory = new OBConsoleDataSourceFactory(new ConnectionConfig(), true, true);
        dataSourceFactory.setEventPublisher(eventPublisher);
        dataSourceFactory.setConnectionExtensionPoint(connectionExtensionPoint);
    }

    @Test
    public void testGetDataSource() throws SQLException {
        DataSource dataSource = dataSourceFactory.getDataSource();
        Connection connection = dataSource.getConnection();
        verify(connectionExtensionPoint).generateJdbcUrl(dataSourceFactory.getHost(), dataSourceFactory.getPort(), dataSourceFactory.getDefaultSchema(), dataSourceFactory.getParameters());
        verify(connectionExtensionPoint).getDriverClassName();
        connection.close();
    }

